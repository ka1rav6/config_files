-- Touchscreen digitizer power policy -- the manual override, and nothing else.
--
-- This file used to be ~190 lines: it discovered every device advertising
-- SW_TABLET_MODE, pre-registered the name of one that does not exist until the
-- first fold, bound switch:on / switch:off to a shell script, and reconciled
-- state at every `hyprctl reload`. All of that now lives in a root service,
-- hypr-digitizerd, which reads the switch itself. What is left here is the one
-- thing a compositor is actually the right place for: a keybind.
--
-- WHY THE COMPOSITOR STOPPED BEING THE EVENT SOURCE
--   Three things the switch binds could not do, all of which the daemon does:
--
--     * The switch does not exist at login. intel_hid registers "Intel HID
--       switches" lazily, on the first fold. Hyprland parses this file once at
--       startup, so a bind could only ever reach it by hardcoding the name and
--       hoping -- which is exactly what the old version did. The daemon holds
--       an inotify watch on /dev/input and picks the device up when the kernel
--       creates it.
--
--     * A switch emits no event for a state that was already true, so a
--       machine booted folded came up with no touch and nothing coming. The
--       old `reconcile` could only guess. The daemon asks the kernel with
--       EVIOCGSW what the switch reads right now.
--
--     * Nothing serialised the old chain -- bind, bash, sudo, bash, one write
--       to /sys -- so two quick folds raced each other. The daemon is one
--       epoll loop, so they cannot.
--
--   None of this was about speed. Hyprland's switch binds already fired on the
--   event; they just could not be correct at the edges.
--
-- EVERYTHING ABOUT WHY THE DIGITIZER IS TURNED OFF AT ALL -- the ~41,600
-- interrupts/sec with nothing touching the panel, the core held out of deep
-- idle, the gentler options that do not work -- is unchanged and still
-- documented at the top of scripts/touchscreen.sh.
--
-- REQUIRES the one-time root install, which is NOT done by this file:
--   sudo ~/.config/hypr/scripts/install-touchscreen.sh
-- Without it the bind still registers and simply reports that the daemon is
-- not reachable, which is the same "safe if the hardware or the install is
-- absent" rule the rest of this config follows.

local home = os.getenv("HOME")
local script = home .. "/.config/hypr/scripts/touchscreen-toggle.sh"

-- The manual escape hatch, and the only way to get touch in laptop mode.
--
-- SUPER + SHIFT + D for "digitizer". SUPER + SHIFT + T would have read better
-- for "touch" but is already the theme toggle (bindings.lua:432), and the
-- plain SUPER + T is windows.tile.
--
-- The override it sets lasts until the next fold or unfold, which is a newer
-- and more explicit statement of intent than the keypress was.
hl.bind(mainMod .. " + SHIFT + D", hl.dsp.exec_cmd(script))
